_Shape _shapeForLevel(int level) {
  // +7 so the first generated level doesn't land on template 0 identity
  // (which is Level 1's exact shape).
  final n = level - kFirstGenerated + 7;
  final base = _templates[n % _templates.length];
  final mirror = (n ~/ _templates.length) % 4; // 0..3
  final flipX = mirror == 1 || mirror == 3;
  final flipY = mirror == 2 || mirror == 3;

  List<int> t(List<int> p) => <int>[
        flipX ? (gridCols - 1 - p[0]) : p[0],
        flipY ? (gridRows - 1 - p[1]) : p[1],
      ];

  return _Shape(
    base.path.map(t).toList(),
    base.spots.map(t).toList(),
  );
}

// --- .tmx emitter --------------------------------------------------------

int _px(int cell) => ((cell + 0.5) * cellSize).round();

String _tmx(int level, _LevelSpec spec, _Shape shape) {
  final polyline =
      shape.path.map((p) => '${_px(p[0])},${_px(p[1])}').join(' ');

  final spots = StringBuffer();
  var id = 2;
  for (final s in shape.spots) {
    spots.writeln(
        '  <object id="${id++}" x="${_px(s[0])}" y="${_px(s[1])}"><point/></object>');
  }

  return '''<?xml version="1.0" encoding="UTF-8"?>
<map version="1.10" tiledversion="1.11.0" orientation="orthogonal" renderorder="right-down" width="$gridCols" height="$gridRows" tilewidth="$cellSize" tileheight="$cellSize" infinite="0" nextlayerid="3" nextobjectid="${id + 1}">
 <properties>
  <property name="title" value="${_escape(_title(level))}"/>
  <property name="background" value="game/level_01_background.png"/>
  <property name="startingLives" type="int" value="${spec.startingLives}"/>
  <property name="startingGold" type="int" value="${spec.startingGold}"/>
  <property name="timeBetweenWaves" type="float" value="${spec.timeBetweenWaves}"/>
  <property name="towers" value="arrow,cannon,flamingArrow"/>
  <property name="enemyHp" type="float" value="${spec.enemyHp.round()}"/>
  <property name="enemySpeed" type="float" value="${spec.enemySpeed.round()}"/>
  <property name="enemyGold" type="int" value="${spec.enemyGold}"/>
  <property name="enemyLives" type="int" value="1"/>
  <property name="waves" value="${spec.waves}"/>
 </properties>
 <objectgroup id="1" name="path">
  <object id="1" name="river" x="0" y="0">
   <polyline points="$polyline"/>
  </object>
 </objectgroup>
 <objectgroup id="2" name="buildspots">
$spots </objectgroup>
</map>
''';
}

