// Generates the campaign levels 4..30 as real Tiled `.tmx` files plus the
// matching `LevelInfo` catalog entries.
//
//   dart run tool/generate_levels.dart
//
// Levels 1-3 are hand-authored and left untouched. Everything this script emits
// is a normal `.tmx` you can still open in Tiled and tweak by hand — rerunning
// the script overwrites those tweaks, so pull a level out of the generated range
// (rename it, add a handcrafted catalog entry) if you want to keep edits.
//
// Tuning lives in two places: [_templates] (path + tower-spot shapes) and
// [_LevelSpec.forLevel] (the difficulty curve).

import 'dart:io';
import 'dart:math' as math;

const int kFirstGenerated = 4;
const int kLastGenerated = 30;

const int gridCols = 20;
const int gridRows = 12;
const int cellSize = 48;

void main() {
  final levelsDir = Directory('assets/levels');
  if (!levelsDir.existsSync()) {
    stderr.writeln('run me from the package root (no assets/levels/)');
    exit(1);
  }

  final catalog = StringBuffer();
  for (var level = kFirstGenerated; level <= kLastGenerated; level++) {
    final spec = _LevelSpec.forLevel(level);
    final shape = _shapeForLevel(level);
    final file = File('assets/levels/${_levelId(level)}.tmx');
    file.writeAsStringSync(_tmx(level, spec, shape));
    stdout.writeln('wrote ${file.path}  '
        '(${spec.waveCount} waves, hp ${spec.enemyHp.round()})');

    catalog.writeln('  LevelInfo(');
    catalog.writeln("    id: '${_levelId(level)}',");
    catalog.writeln("    tmxAsset: 'assets/levels/${_levelId(level)}.tmx',");
    catalog.writeln("    title: '${_escape(_title(level))}',");
    catalog.writeln("    tagline: '${_escape(spec.tagline)}',");
    catalog.writeln('  ),');
  }

  File('lib/features/game/data/levels/generated_levels.dart').writeAsStringSync(
    "// GENERATED by tool/generate_levels.dart — do not edit by hand.\n"
    "// Run `dart run tool/generate_levels.dart` to regenerate.\n\n"
    "import '../../domain/models/level_info.dart';\n\n"
    "/// Campaign levels $kFirstGenerated..$kLastGenerated, procedurally generated.\n"
    'const List<LevelInfo> kGeneratedLevels = <LevelInfo>[\n'
    '$catalog'
    '];\n',
  );
  stdout.writeln('wrote lib/features/game/data/levels/generated_levels.dart');
}

String _levelId(int level) => 'level_${level.toString().padLeft(2, '0')}';

// --- difficulty curve -------------------------------------------------------

class _LevelSpec {
  _LevelSpec({
    required this.startingLives,
    required this.startingGold,
    required this.timeBetweenWaves,
    required this.enemyHp,
    required this.enemySpeed,
    required this.enemyGold,
    required this.waveCount,
    required this.waves,
    required this.tagline,
  });

  final int startingLives;
  final int startingGold;
  final double timeBetweenWaves;
  final double enemyHp;
  final double enemySpeed;
  final int enemyGold;
  final int waveCount;
  final String waves;
  final String tagline;

  factory _LevelSpec.forLevel(int level) {
    final l = level.toDouble();

    // HP: gentle at first, then a quadratic ramp so towers stay relevant.
    final hp = 24 + (l - 1) * 10 + (l - 1) * (l - 1) * 0.5;
    final speed = math.min(55 + l * 0.8, 96).toDouble();
    final gold = (7 + level ~/ 4);
    final waveCount = (6 + (l - 4) * 0.45).round().clamp(6, 20);

    final waves = <String>[];
    for (var w = 1; w <= waveCount; w++) {
      final isLast = w == waveCount;
      final count = (5 + w + level ~/ 3) + (isLast ? 4 : 0);
      final interval =
          (0.85 - l * 0.013 - w * 0.02).clamp(0.22, 0.9).toStringAsFixed(2);
      // Every 4th wave (and the finale) comes as a tighter double burst.
      if (isLast || w % 4 == 0) {
        final half = (count / 2).ceil();
        waves.add('$half@$interval+${count - half}@${(double.parse(interval) *
            1.6).clamp(0.3, 1.2).toStringAsFixed(2)}');
      } else {
        waves.add('$count@$interval');
      }
    }

    return _LevelSpec(
      startingLives: 20 + (level ~/ 10) * 2,
      startingGold: 100 + level * 3,
      timeBetweenWaves: 3,
      enemyHp: hp,
      enemySpeed: speed,
      enemyGold: gold,
      waveCount: waveCount,
      waves: waves.join(';'),
      tagline: _tagline(level, waveCount),
    );
  }
}

String _tagline(int level, int waveCount) {
  if (level <= 8) {
    return 'Sức ép tăng dần — $waveCount đợt heo, đặt tháp sớm và chắc.';
  }
  if (level <= 16) {
    return 'Heo dày mình hơn. Ghép Đại Bác với Tên Lửa để dọn cả đàn.';
  }
  if (level <= 24) {
    return '$waveCount đợt liên hoàn, có nhịp dồn kép. Giữ vàng cho nâng cấp.';
  }
  return 'Cửa ải cuối: heo thép, tới như thác. Không được rò một con.';
}

