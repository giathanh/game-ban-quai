const List<String> _names = <String>[
  'Dòng xoáy', 'Bến vắng', 'Thác Bạc', 'Kênh Đôi', 'Vũng Lầy', 'Cầu Gãy',
  'Rừng Ngập', 'Đầm Sen', 'Vịnh Cạn', 'Suối Đá', 'Ghềnh Thác', 'Chợ Nổi',
  'Cồn Cát', 'Lạch Sâu', 'Đập Tràn', 'Cửa Cống', 'Bãi Sậy', 'Xẻo Quýt',
  'Rạch Chằng', 'Ngã Bảy', 'Hồ Gió', 'Vực Xoáy', 'Doi Đất', 'Bàu Sấu',
  'Cửa Đại', 'Sóng Thần', 'Trùng Khơi',
];

String _title(int level) {
  final name = _names[(level - kFirstGenerated) % _names.length];
  return 'Màn $level — $name';
}

String _escape(String s) => s
    .replaceAll('&', '&amp;')
    .replaceAll('"', '&quot;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');
